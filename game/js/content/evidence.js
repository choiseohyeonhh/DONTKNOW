/* 화면에서 항목을 열었을 때. 여러 개를 받는다. */
LM.C.see = function () {
  if (!LM.seen) return;
  for (let i = 0; i < arguments.length; i++) {
    const v = arguments[i];
    if (!v) continue;
    if (Array.isArray(v)) v.forEach((x) => LM.C.see(x));
    else LM.seen(v);
  }
};
